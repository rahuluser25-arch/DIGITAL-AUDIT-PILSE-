import { CATEGORY_META, type AuditResult, type CompetitorComparisonData } from '../types/audit';

interface PrintableReportProps {
  audit: AuditResult;
  competitor: CompetitorComparisonData | null;
}

export function PrintableReport({ audit, competitor }: PrintableReportProps) {
  const formattedDate = new Date(audit.timestamp).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  return (
    <div className="print-only hidden bg-white text-slate-900">
      <div className="border-b border-slate-300 pb-4">
        <div className="flex items-baseline justify-between">
          <h1 className="text-2xl font-bold">Digital Audit Pulse Report</h1>
          <span className="font-mono text-xs text-slate-500">{formattedDate}</span>
        </div>
        <p className="mt-1 text-sm text-slate-600">
          {audit.input.businessName} · {audit.input.url} · {audit.input.industry} · Goal:{' '}
          {audit.input.mainGoal}
        </p>
      </div>

      <div className="mt-5 flex items-center justify-between rounded-lg border border-slate-200 p-4">
        <div className="max-w-lg">
          <p className="text-xs font-semibold text-slate-500">Executive Summary</p>
          <p className="mt-1 text-sm leading-relaxed text-slate-800">{audit.executiveSummary}</p>
        </div>
        <div className="text-right">
          <p className="text-xs font-semibold text-slate-500">Overall Pulse Score</p>
          <p className="font-mono text-4xl font-bold text-slate-900 tabular-nums">
            {audit.overallScore}/100
          </p>
        </div>
      </div>

      <div className="mt-6">
        <h2 className="text-base font-bold">Category Breakdown</h2>
        <table className="mt-2 w-full border-collapse text-left text-xs">
          <thead>
            <tr className="border-b border-slate-300 text-slate-600">
              <th className="py-2">Category</th>
              <th className="py-2">Status</th>
              <th className="py-2 text-right">Score</th>
              <th className="py-2 pl-4">Summary</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-200">
            {audit.categories.map((cat) => (
              <tr key={cat.id}>
                <td className="py-2 font-semibold">{cat.name}</td>
                <td className="py-2">{cat.status}</td>
                <td className="py-2 text-right font-mono font-bold tabular-nums">{cat.score}</td>
                <td className="py-2 pl-4 text-slate-700">{cat.summary}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {competitor && (
        <div className="print-break-avoid mt-6 rounded-lg border border-slate-200 p-4">
          <h2 className="text-base font-bold">
            Competitor Benchmark: {competitor.competitorName} ({competitor.overallScore}/100)
          </h2>
          <p className="mt-1 text-xs text-slate-700">{competitor.summary}</p>
        </div>
      )}

      <div className="mt-6">
        <h2 className="text-base font-bold">Top 5 Priority Quick Wins</h2>
        <div className="mt-2 space-y-2.5">
          {audit.actionPlan.map((win) => (
            <div key={win.id} className="print-break-avoid rounded-lg border border-slate-200 p-3">
              <div className="flex items-center justify-between text-xs">
                <span className="font-bold">
                  0{win.rank}. {win.title}
                </span>
                <span className="text-slate-600">
                  Impact: {win.impact} · Effort: {win.effort} · {win.estimatedLift}
                </span>
              </div>
              <p className="mt-1 text-xs text-slate-700">{win.description}</p>
            </div>
          ))}
        </div>
      </div>

      <div className="mt-6">
        <h2 className="text-base font-bold">Detailed Findings</h2>
        <div className="mt-2 space-y-2.5">
          {audit.findings.map((f) => (
            <div key={f.id} className="print-break-avoid border-b border-slate-200 pb-2.5">
              <p className="text-xs font-semibold text-slate-600">
                {f.severity} Severity · {CATEGORY_META[f.categoryId]?.label ?? f.categoryId}
              </p>
              <p className="text-sm font-bold">{f.title}</p>
              <p className="mt-0.5 text-xs text-slate-700">{f.explanation}</p>
              <p className="mt-0.5 text-xs font-medium text-slate-900">
                Fix: {f.recommendation}
              </p>
            </div>
          ))}
        </div>
      </div>

      <p className="mt-6 border-t border-slate-200 pt-3 text-[11px] text-slate-500">
        Disclaimer: This report was generated by Digital Audit Pulse using AI-assisted analysis and
        observable public webpage signals. Scores are estimates intended to guide prioritization.
      </p>
    </div>
  );
}
